import { readFile } from 'node:fs/promises';

// Editorial preparation and local preview only. Production reads the database;
// this module is never imported by src/lib/public-content.ts or its callers.
export async function loadChatFirstServices({ published = false } = {}) {
  const catalogue = JSON.parse(await readFile(new URL('../src/data/services.json', import.meta.url), 'utf8'));
  const details = JSON.parse(await readFile(new URL('../src/data/serviceDetails.json', import.meta.url), 'utf8'));
  if (!Array.isArray(catalogue.services) || catalogue.services.length !== 6) throw new Error('Expected six editorial services');
  const slugs = new Set();
  return catalogue.services.map((service, index) => {
    const detail = details[service.id];
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(service.id) || slugs.has(service.id) || !detail) throw new Error('Invalid editorial service');
    slugs.add(service.id);
    for (const field of ['title','titleEn','description','descriptionEn','chatMessage','chatMessageEn']) {
      if (typeof service[field] !== 'string' || !service[field].trim()) throw new Error('Missing bilingual catalogue text');
    }
    for (const field of ['subtitle','subtitleEn','hero','heroEn']) {
      if (typeof detail[field] !== 'string' || !detail[field].trim()) throw new Error('Missing bilingual service details');
    }
    const blocks = field => {
      if (!Array.isArray(detail[field]) || detail[field].length < 1 || detail[field].length > 20) throw new Error('Invalid service blocks');
      return detail[field].map(block => {
        if (typeof block.title !== 'string' || !block.title.trim() || typeof block.description !== 'string' || !block.description.trim()) throw new Error('Incomplete service block');
        return { title: block.title, description: block.description, ...(field.startsWith('process') ? { step: String(block.step) } : {}) };
      });
    };
    return {
      id: `00000000-0000-4000-8000-${String(920 + index).padStart(12, '0')}`,
      slug: service.id, title: service.title, title_en: service.titleEn,
      description: service.description, description_en: service.descriptionEn,
      icon: service.icon, highlighted: service.highlighted === true, sort_order: index,
      chat_message: service.chatMessage, cta_message: service.chatMessage, cta_message_en: service.chatMessageEn,
      tagline: detail.subtitle, tagline_en: detail.subtitleEn,
      hero_description: detail.hero, hero_description_en: detail.heroEn,
      features: blocks('features'), features_en: blocks('featuresEn'),
      process: blocks('process'), process_en: blocks('processEn'),
      is_published: published === true,
    };
  });
}

export function renderServicesCatalogueSql(services) {
  if (services.some(service => service.is_published !== false)) throw new Error('Editorial import must remain unpublished');
  const payload = JSON.stringify(services);
  if (payload.includes('$akrasia_services$')) throw new Error('Unexpected SQL delimiter');
  const fields = ['id','slug','title','title_en','description','description_en','icon','highlighted','sort_order','chat_message','cta_message','cta_message_en','tagline','tagline_en','hero_description','hero_description_en','features','features_en','process','process_en','is_published'];
  return `-- Optional editorial import generated by scripts/prepare-services-catalogue.mjs.
-- Apply separately after migration-v16 or later. Not part of the migration manifest.
-- Inserts six drafts only. Existing slugs, edits and publication decisions are preserved.
-- Review each draft in the admin panel and approve publication explicitly.
BEGIN;
INSERT INTO public.services (${fields.join(',')})
SELECT ${fields.map(field => `draft.${field}`).join(',')}
FROM jsonb_populate_recordset(NULL::public.services, $akrasia_services$${payload}$akrasia_services$::jsonb) AS draft
ON CONFLICT (slug) DO NOTHING;
COMMIT;
`;
}
